  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  let lang = LANGS.includes(saved) ? saved : LANGS.includes(nav) ? nav : 'en';
  const ix = () => LANGS.indexOf(lang);
  const t = (k, v) => {
    const row = D[k];
    let s = row ? (row[ix()] ?? row[0]) : k;
    if (v) s = s.replace(/\{(\w+)\}/g, (m, x) => v[x] ?? m);
    return s;
  };
